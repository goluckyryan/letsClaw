"""Reading config.yaml and turning it into engines.

Everything between the file on disk and a usable LLMEngine: load it, read the
webui presentation keys out of it, coerce the numbers people actually write,
build one engine per model, and say what changed across a reload.

None of it touches a Session, which is why it is here rather than in core —
server.py was already reaching past core's API for core.known_models and
core.PIN_KEYS, and that is the tell that this was a module all along.

Synchronous and network-free throughout. build_all_engines doubles as the
config validator: building the engines is a far better check than inspecting
keys, because it is the same code path a real turn will run.
"""
import logging
import re
import time
from pathlib import Path

import yaml

import paths
from llm_engine import LLMEngine

logger = logging.getLogger("letclaw.config")

CONFIG_PATH = paths.REPO_ROOT / "config.yaml"

DEFAULT_CONTEXT_LENGTH = 12000
# Seconds held back from turn_timeout so the answer still fits inside the wall
# after a long think.
DEFAULT_ANSWER_TIME_RESERVE = 120


# The top-level sections the code reads as mappings. A key written with no
# value (`core:`) parses to None, and every reader reaches into it the way it
# would a dict — `config.get("core", {})` returns the None that is *stored*,
# not the default, because the key is present. Normalising here is what keeps
# that from being each reader's problem: the same nine sections docs/config.html
# documents, and no others.
SECTION_KEYS = ("behavior", "models", "core", "tools", "conversation",
                "memory", "logging", "webui", "discord")


def _normalize(cfg):
    """A parsed config with its empty sections standing as dicts.

    Only SECTION_KEYS, deliberately. Normalising every None would turn
    `default_model:` (a key that legitimately holds nothing) into a dict, and a
    dict is unhashable — `{}` as a model name raises where it used to fall back.
    A section is a mapping by the shape of every config that has one; anything
    else the user wrote is left exactly as it is.
    """
    if not isinstance(cfg, dict):
        # A file holding a bare string or a list is not a config; reading it as
        # one would fail somewhere far from the cause.
        return {}
    for key in SECTION_KEYS:
        if cfg.get(key) is None:
            cfg[key] = {}
    return cfg


def load_config(path=None):
    """Read config.yaml. Raises rather than exiting — a service must not sys.exit."""
    path = Path(path or CONFIG_PATH)
    if not path.exists():
        raise FileNotFoundError(f"No config.yaml at {path} "
                                "(copy config.example.yaml and customise)")
    with open(path) as f:
        return _normalize(yaml.safe_load(f) or {})


def has_models(cfg):
    """Whether this config names at least one model the core could use.

    The test for "is there a config here at all" — an empty file, a file of
    comments, or one whose models: section is blank all mean the core has
    nothing to serve, which is the case ensure_config exists to recover from.
    """
    return bool(known_models(cfg))


# What a fresh install gets. Deliberately minimal and deliberately unusable
# until one line is filled in: a generated config must not quietly point a
# session at a server the person never chose, and a model entry with no
# base_url is refused by build_engine with a message that says what to do.
