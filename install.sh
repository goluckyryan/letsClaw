#!/bin/bash
# letsClaw — install as a systemd service: letsClaw.service
#
#   ./install.sh                 --user unit (no root): ~/.config/systemd/user/
#   ./install.sh --system        system unit (needs sudo): /etc/systemd/system/
#   ./install.sh [--system] --no-start
#   ./install.sh --uninstall     remove whichever is present (both, if both)
#
# Both units run ./serve.sh — the core, plus the Discord bot when the config
# enables it. The user unit runs as you and starts at login; it survives
# reboot only if linger is on (checked below). The system unit runs as you
# too (User= in the file) and starts at boot regardless of login.
#
# Logs:  journalctl [--user] -u letsClaw -f   (also logs/letclaw-core.log)
# State: systemctl [--user] status letsClaw
#
# Re-run ./install.sh after a git pull to refresh the unit (it is generated,
# so do not hand-edit it).
set -euo pipefail
cd "$(dirname "$0")"

DIR=$(pwd)
RUN_USER=$(id -un)
RUN_HOME=$(getent passwd "$RUN_USER" | cut -d: -f6)
USER_UNIT="$HOME/.config/systemd/user/letsClaw.service"
SYSTEM_UNIT="/etc/systemd/system/letsClaw.service"

system=0
no_start=0
uninstall=0
for a in "$@"; do
  case "$a" in
    --system|-system) system=1 ;;
    --no-start)       no_start=1 ;;
    --uninstall)      uninstall=1 ;;
    *) echo "usage: $0 [--system] [--no-start | --uninstall]" >&2; exit 1 ;;
  esac
done

# Root helper, only ever used for the system unit: plain if we are root,
# sudo if it is passwordless, else empty (staged-file fallback).
SUDO=""
if [ "$(id -u)" -ne 0 ]; then
  sudo -n true 2>/dev/null && SUDO="sudo" || true
fi

# --- 1. environment ----------------------------------------------------------
setup_env() {
  if [ ! -x .venv/bin/python ]; then
    echo "→ creating .venv (python3 -m venv)"
    python3 -m venv .venv
    .venv/bin/python -m pip install --upgrade pip
  fi
  if ! .venv/bin/python -c "import aiohttp, openai, yaml, tiktoken" 2>/dev/null; then
    echo "→ installing dependencies (requirements.txt)"
    .venv/bin/python -m pip install -r requirements.txt
  fi
  # The bot is a separate dependency: only required if the config will start
  # it. The same question serve.sh asks, asked by the same script — this used
  # to be a second hand-written copy of that check, and it was the copy that
  # had not learned to tell an exception from an answer: `else 1` plus a
  # discarded stderr meant a renamed import, a broken config, anything at all,
  # arrived here looking exactly like "no token". discord.py then went
  # uninstalled on a fresh install with the bot enabled, and the reason for it
  # was thrown away. Codes: 0 install it, 2 disabled, 3 no token, 4 no config
  # yet (setup_config has not run), anything else = the probe itself raised.
  #
  # Declared before the assignment rather than on it, because `local x=$(...)`
  # reports local's own status — always 0 — and the status is the whole answer
  # here. And `|| probe_status=$?` rather than a bare assignment, because this
  # script runs under set -e and every verdict except 0 is a non-zero exit: an
  # unguarded assignment would end the install on a config that simply has the
  # bot switched off.
  local probe_err probe_status=0
  probe_err=$(.venv/bin/python source/discord_probe.py 2>&1 >/dev/null) \
    || probe_status=$?
  case "$probe_status" in
    0) if ! .venv/bin/python -c "import discord" 2>/dev/null; then
         echo "→ discord is enabled in config.yaml — installing discord.py"
         .venv/bin/python -m pip install -r requirements.txt
       fi ;;
    2|3|4) ;;    # a real answer, and the answer is "the bot is not wanted"
    *) echo "   ⚠️  could not read the discord config — skipping discord.py"
       if [ -n "$probe_err" ]; then
         printf '%s\n' "$probe_err" | sed 's/^/      /'
       fi ;;
  esac
}

# --- 2. config ----------------------------------------------------------------
setup_config() {
  if [ ! -f config.yaml ]; then
    cp config.example.yaml config.yaml
    echo "→ created config.yaml from config.example.yaml — edit it before starting"
  fi
}

# --- 3. the unit ---------------------------------------------------------------
# One template; the system unit adds User= and HOME (systemd system services
# do not set either), and wants multi-user.target instead of default.target.
write_unit() {
  local body wantedby
  if [ "$system" = 1 ]; then
    wantedby="multi-user.target"
    body="User=$RUN_USER
Environment=HOME=$RUN_HOME
"
  else
    wantedby="default.target"
    body=""
  fi
  local stage
  stage=$(mktemp)
  cat > "$stage" <<EOF
# letsClaw — generated by $DIR/install.sh; re-run that script to refresh.
[Unit]
Description=letsClaw core service (and Discord bot)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
${body}WorkingDirectory=$DIR
ExecStart=$DIR/serve.sh
Restart=on-failure
RestartSec=3
TimeoutStopSec=30

[Install]
WantedBy=$wantedby
EOF
  local dest
  if [ "$system" = 1 ]; then dest="$SYSTEM_UNIT"; else dest="$USER_UNIT"; fi

  if [ "$system" = 1 ]; then
    if [ "$(id -u)" -eq 0 ]; then
      install -m 0644 "$stage" "$dest"; rm -f "$stage"
    elif [ -n "$SUDO" ]; then
      $SUDO install -m 0644 "$stage" "$dest"; rm -f "$stage"
    else
      mv "$stage" "$DIR/letsClaw.service.generated"
      echo "⚠️  --system needs root and sudo asked for a password."
      echo "   staged $DIR/letsClaw.service.generated — finish with:"
      echo "     sudo install -m 0644 $DIR/letsClaw.service.generated $SYSTEM_UNIT"
      echo "     sudo systemctl daemon-reload"
      echo "     sudo systemctl enable --now letsClaw.service"
      exit 0
    fi
  else
    mkdir -p "$(dirname "$dest")"
    mv "$stage" "$dest"
  fi
  echo "→ wrote $dest"
}

# --- 4. is the core already running? (would collide on the port) ---------------
port_busy() {
  local port
  port=$(.venv/bin/python -c "
import sys; sys.path.insert(0, 'source')
from config import load_config
print((load_config(None).get('core') or {}).get('port', 8770))" 2>/dev/null || echo 8770)
  ss -ltn 2>/dev/null | grep -q ":$port " && return 0 || return 1
}

# --- 5. is the OTHER flavour already installed? (two units = port fight) -------
other_unit_present() {
  if [ "$system" = 1 ]; then
    [ -e "$USER_UNIT" ] || systemctl --user list-unit-files letsClaw.service 2>/dev/null | grep -q letsClaw
  else
    [ -e "$SYSTEM_UNIT" ] || systemctl list-unit-files letsClaw.service 2>/dev/null | grep -q letsClaw
  fi
}

# --- uninstall: whatever is present, both if both -------------------------------
if [ "$uninstall" = 1 ]; then
  found=0
  if [ -e "$USER_UNIT" ] || systemctl --user list-unit-files letsClaw.service 2>/dev/null | grep -q letsClaw; then
    found=1
    echo "→ removing user unit"
    systemctl --user disable --now letsClaw.service 2>/dev/null || true
    rm -f "$USER_UNIT"
    systemctl --user daemon-reload
  fi
  if [ -e "$SYSTEM_UNIT" ] || systemctl list-unit-files letsClaw.service 2>/dev/null | grep -q letsClaw; then
    found=1
    if [ -z "$SUDO" ] && [ "$(id -u)" -ne 0 ]; then
      echo "⚠️  a system unit is installed but sudo needs a password:"
      echo "     sudo systemctl disable --now letsClaw.service"
      echo "     sudo rm -f $SYSTEM_UNIT && sudo systemctl daemon-reload"
      exit 1
    fi
    echo "→ removing system unit"
    $SUDO systemctl disable --now letsClaw.service 2>/dev/null || true
    $SUDO rm -f "$SYSTEM_UNIT"
    $SUDO systemctl daemon-reload
  fi
  if [ "$found" = 1 ]; then echo "done. venv, config and state are untouched."
  else echo "nothing to uninstall — no letsClaw.service found."; fi
  exit 0
fi

# --- install --------------------------------------------------------------------
if other_unit_present; then
  echo "⚠️  the other flavour of letsClaw.service is already installed."
  echo "   two units would fight over the core's port — uninstall first:"
  echo "     ./install.sh --uninstall"
  exit 1
fi

echo "→ environment"
setup_env
setup_config
write_unit

if [ "$system" = 0 ]; then
  # Linger is what makes a --user unit survive logout/reboot. It is a
  # per-user flag set by root; if it is off the service still works, it
  # just stops when the session ends — one sudo line fixes it.
  if ! loginctl show-user "$RUN_USER" 2>/dev/null | grep -q '^Linger=yes'; then
    echo "⚠️  linger is off — the service stops when you log out."
    echo "   fix:  sudo loginctl enable-linger $RUN_USER"
  fi
  systemctl --user daemon-reload
  SYSCTL="systemctl --user"
else
  $SUDO systemctl daemon-reload
  SYSCTL="$SUDO systemctl"
fi

if [ "$no_start" = 1 ]; then
  $SYSCTL enable letsClaw.service
  echo "→ enabled. start it with:  $SYSCTL start letsClaw.service"
  exit 0
fi

if port_busy; then
  echo
  echo "⚠️  the core's port is already in use (a manual ./serve.sh?)."
  echo "   stop it first, then:  $SYSCTL start letsClaw.service"
  $SYSCTL enable letsClaw.service
  exit 0
fi

JCTL="journalctl"
[ "$system" = 1 ] && JCTL="$SUDO journalctl"
$SYSCTL enable --now letsClaw.service
sleep 2
$SYSCTL status letsClaw.service --no-pager | head -12 || true
echo
echo "logs:  $JCTL -u letsClaw -f"
