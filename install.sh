#!/bin/bash
# letsClaw — install as a systemd user service: letsClaw.service
#
#   ./install.sh              venv + config check, write the unit, enable and start
#   ./install.sh --no-start   same, but leave it stopped (enabled for next login)
#   ./install.sh --uninstall  stop, disable and remove the unit
#
# A --user unit: no root at all. It lives at
# ~/.config/systemd/user/letsClaw.service, runs ./serve.sh as you (the core,
# plus the Discord bot when the config enables it), and starts at boot only
# if linger is on — checked below; if it is off the service stops on logout.
#
# Logs:  journalctl --user -u letsClaw -f    (the core also writes logs/letclaw.log)
# State: systemctl --user status letsClaw
#
# Re-run ./install.sh after a git pull to refresh the unit (it is generated,
# so do not hand-edit it).
set -euo pipefail
cd "$(dirname "$0")"

DIR=$(pwd)
USERSYSTEMD="$HOME/.config/systemd/user"
UNIT="$USERSYSTEMD/letsClaw.service"
RUN_USER=$(id -un)

no_start=0
uninstall=0
case "${1:-}" in
  --uninstall) uninstall=1 ;;
  --no-start)  no_start=1 ;;
  "")          ;;
  *) echo "usage: $0 [--no-start | --uninstall]" >&2; exit 1 ;;
esac

# --- 1. environment ----------------------------------------------------------
setup_env() {
  if [ ! -x .venv/bin/python ]; then
    echo "→ creating .venv (python3 -m venv)"
    python3 -m venv .venv
    .venv/bin/python -m pip install --upgrade pip
  fi
  if ! .venv/bin/python -c "import aiohttp, openai, yaml, tiktoken" 2>/dev/null; then
    echo "→ installing dependencies (requirements.txt)"
    .venv/bin/python -m pip install -r requirements.txt
  fi
  # The bot is a separate dependency: only required if the config will start
  # it, mirroring serve.sh's own check (enabled + token present).
  if .venv/bin/python -c "
import sys
sys.path.insert(0, 'source')
from core import load_config
cfg = load_config(None)
d = cfg.get('discord') or {}
sys.exit(0 if d.get('enabled', True) is not False and
             str(d.get('token') or '').strip() else 1)
" 2>/dev/null; then
    if ! .venv/bin/python -c "import discord" 2>/dev/null; then
      echo "→ discord is enabled in config.yaml — installing discord.py"
      .venv/bin/python -m pip install -r requirements.txt
    fi
  fi
}

# --- 2. config ----------------------------------------------------------------
setup_config() {
  if [ ! -f config.yaml ]; then
    cp config.example.yaml config.yaml
    echo "→ created config.yaml from config.example.yaml — edit it before starting"
  fi
}

# --- 3. the unit ---------------------------------------------------------------
write_unit() {
  mkdir -p "$USERSYSTEMD"
  cat > "$UNIT" <<EOF
# letsClaw — generated by $DIR/install.sh; re-run that script to refresh.
[Unit]
Description=letsClaw core service (and Discord bot)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
WorkingDirectory=$DIR
ExecStart=$DIR/serve.sh
Restart=on-failure
RestartSec=3
TimeoutStopSec=30

[Install]
WantedBy=default.target
EOF
  echo "→ wrote $UNIT"
}

# --- 4. is the core already running? (would collide on the port) ---------------
port_busy() {
  local port
  port=$(.venv/bin/python -c "
import sys; sys.path.insert(0, 'source')
from core import load_config
print((load_config(None).get('core') or {}).get('port', 8770))" 2>/dev/null || echo 8770)
  ss -ltn 2>/dev/null | grep -q ":$port " && return 0 || return 1
}

# --- uninstall ------------------------------------------------------------------
if [ "$uninstall" = 1 ]; then
  if [ ! -e "$UNIT" ] && ! systemctl --user list-unit-files letsClaw.service 2>/dev/null | grep -q letsClaw; then
    echo "nothing to uninstall — $UNIT is not present."
    exit 0
  fi
  echo "→ uninstalling letsClaw.service"
  systemctl --user disable --now letsClaw.service || true
  rm -f "$UNIT"
  systemctl --user daemon-reload
  echo "done. venv, config and state are untouched."
  exit 0
fi

# --- install --------------------------------------------------------------------
echo "→ environment"
setup_env
setup_config
write_unit

# Linger is what makes a --user unit survive logout/reboot. It is a per-user
# flag set by root; if it is off the service still works, it just stops when
# the session ends — one sudo line fixes it.
if ! loginctl show-user "$RUN_USER" 2>/dev/null | grep -q '^Linger=yes'; then
  echo "⚠️  linger is off — the service stops when you log out."
  echo "   fix:  sudo loginctl enable-linger $RUN_USER"
fi

systemctl --user daemon-reload

if [ "$no_start" = 1 ]; then
  systemctl --user enable letsClaw.service
  echo "→ enabled. start it with:  systemctl --user start letsClaw.service"
  exit 0
fi

if port_busy; then
  echo
  echo "⚠️  the core's port is already in use (a manual ./serve.sh?)."
  echo "   stop it first, then:  systemctl --user start letsClaw.service"
  systemctl --user enable letsClaw.service
  exit 0
fi

systemctl --user enable --now letsClaw.service
sleep 2
systemctl --user status letsClaw.service --no-pager | head -12 || true
echo
echo "logs:  journalctl --user -u letsClaw -f"
