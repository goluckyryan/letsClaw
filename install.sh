#!/bin/bash
# letsClaw — install as a systemd service: letsClaw.service
#
#   ./install.sh              venv + config check, write the unit, enable and start
#   ./install.sh --no-start   same, but leave it stopped (enabled for next boot)
#   ./install.sh --uninstall  stop, disable and remove the unit
#
# The unit runs ./serve.sh — the core, plus the Discord bot when the config
# enables it — as the user who ran this script. Only writing the unit file
# and enabling it need root; the service itself runs as you.
#
# Logs:  journalctl -u letsClaw -f        (the core also writes logs/letclaw.log)
# State: systemctl status letsClaw
#
# Re-run ./install.sh after a git pull to refresh the unit (it is generated,
# so do not hand-edit it).
set -euo pipefail
cd "$(dirname "$0")"

DIR=$(pwd)
UNIT=/etc/systemd/system/letsClaw.service
RUN_USER=$(id -un)
RUN_HOME=$(getent passwd "$RUN_USER" | cut -d: -f6)

no_start=0
case "${1:-}" in
  --uninstall) uninstall=1 ;;
  --no-start)  no_start=1 ;;
  "")          ;;
  *) echo "usage: $0 [--no-start | --uninstall]" >&2; exit 1 ;;
esac

# --- root helper: plain if we are root, sudo if we can, else a note ---------
SUDO=""
if [ "$(id -u)" -ne 0 ]; then
  if sudo -n true 2>/dev/null; then
    SUDO="sudo"
  else
    SUDO=""
  fi
fi

root_or_print() {
  # run $@ as root; if we cannot, print the command for the user to run
  if [ -n "$SUDO" ]; then
    $SUDO "$@"
  else
    echo "needs root — run:"
    echo "  sudo $*"
    return 1
  fi
}

# --- 1. environment ----------------------------------------------------------
setup_env() {
  if [ ! -x .venv/bin/python ]; then
    echo "→ creating .venv (python3 -m venv)"
    python3 -m venv .venv
    .venv/bin/python -m pip install --upgrade pip
  fi
  if ! .venv/bin/python -c "import aiohttp, openai, yaml, tiktoken" 2>/dev/null; then
    echo "→ installing dependencies (requirements.txt)"
    .venv/bin/python -m pip install -r requirements.txt
  fi
  # The bot is a separate dependency: only required if the config will start
  # it, mirroring serve.sh's own check (enabled + token present).
  if .venv/bin/python -c "
import sys
sys.path.insert(0, 'source')
from core import load_config
cfg = load_config(None)
d = cfg.get('discord') or {}
sys.exit(0 if d.get('enabled', True) is not False and
             str(d.get('token') or '').strip() else 1)
" 2>/dev/null; then
    if ! .venv/bin/python -c "import discord" 2>/dev/null; then
      echo "→ discord is enabled in config.yaml — installing discord.py"
      .venv/bin/python -m pip install -r requirements.txt
    fi
  fi
}

# --- 2. config ----------------------------------------------------------------
setup_config() {
  if [ ! -f config.yaml ]; then
    cp config.example.yaml config.yaml
    echo "→ created config.yaml from config.example.yaml — edit it before starting"
  fi
}

# --- 3. the unit ---------------------------------------------------------------
write_unit() {
  local stage
  stage=$(mktemp)
  cat > "$stage" <<EOF
# letsClaw — generated by $DIR/install.sh; re-run that script to refresh.
[Unit]
Description=letsClaw core service (and Discord bot)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=$RUN_USER
WorkingDirectory=$DIR
Environment=HOME=$RUN_HOME
ExecStart=$DIR/serve.sh
Restart=on-failure
RestartSec=3
TimeoutStopSec=30

[Install]
WantedBy=multi-user.target
EOF
  if [ -n "$SUDO" ] || [ "$(id -u)" -eq 0 ]; then
    if [ "$(id -u)" -eq 0 ]; then install -m 0644 "$stage" "$UNIT"
    else sudo install -m 0644 "$stage" "$UNIT"; fi
    rm -f "$stage"
    echo "→ wrote $UNIT"
  else
    mv "$stage" "$DIR/letsClaw.service.generated"
    echo "→ cannot write $UNIT without root; staged $DIR/letsClaw.service.generated"
    echo "  run:  sudo install -m 0644 $DIR/letsClaw.service.generated $UNIT"
    return 1
  fi
}

# --- 4. is the core already running? (would collide on the port) ---------------
port_busy() {
  local port
  port=$(.venv/bin/python -c "
import sys; sys.path.insert(0, 'source')
from core import load_config
print((load_config(None).get('core') or {}).get('port', 8770))" 2>/dev/null || echo 8770)
  ss -ltn 2>/dev/null | grep -q ":$port " && return 0 || return 1
}

# --- uninstall ------------------------------------------------------------------
if [ "${uninstall:-0}" = 1 ]; then
  if [ ! -e "$UNIT" ] && ! systemctl list-unit-files letsClaw.service 2>/dev/null | grep -q letsClaw; then
    echo "nothing to uninstall — $UNIT is not present."
    exit 0
  fi
  echo "→ uninstalling letsClaw.service"
  root_or_print systemctl disable --now letsClaw.service || exit 1
  root_or_print rm -f "$UNIT" || exit 1
  root_or_print systemctl daemon-reload || exit 1
  echo "done. venv, config and state are untouched."
  exit 0
fi

# --- install --------------------------------------------------------------------
echo "→ environment"
setup_env
setup_config

if ! write_unit; then
  echo
  echo "install.sh stopped: the unit needs root. Once it is in place:"
  echo "  sudo systemctl daemon-reload"
  echo "  sudo systemctl enable --now letsClaw.service"
  exit 0
fi

$SUDO systemctl daemon-reload

if [ "$no_start" = 1 ]; then
  $SUDO systemctl enable letsClaw.service
  echo "→ enabled. start it with:  sudo systemctl start letsClaw.service"
  exit 0
fi

if port_busy; then
  echo
  echo "⚠️  the core's port is already in use (a manual ./serve.sh?)."
  echo "   stop it first, then:  sudo systemctl start letsClaw.service"
  $SUDO systemctl enable letsClaw.service
  exit 0
fi

$SUDO systemctl enable --now letsClaw.service
sleep 2
$SUDO systemctl status letsClaw.service --no-pager | head -12 || true
echo
echo "logs:  journalctl -u letsClaw -f"
